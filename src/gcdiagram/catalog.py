"""Glyph catalog: maps figures and board furniture to font glyphs and outlines.

The catalog is generated by tools/build_catalog.py; see ARCHITECTURE.md section 4.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from importlib import resources
from typing import cast

from .board import Figure, Piece, Shade, Special, SpecialColor


@dataclass(frozen=True, slots=True)
class Glyph:
    key: str
    font: str  # "D", "X" or "Y"
    code: int
    outline: str  # outline id
    bbox: tuple[int, int, int, int] | None  # cell coordinates; None for blank glyphs
    dx: int = 0  # correction already applied to the outline; kern by dx when typesetting


class Catalog:
    def __init__(self, data: dict) -> None:
        self.cell: int = data["cell"]
        self.fonts: dict[str, str] = data["fonts"]
        self.outlines: dict[str, str] = data["outlines"]
        self.glyphs: dict[str, Glyph] = {
            key: Glyph(
                key=key,
                font=g["font"],
                code=g["code"],
                outline=g["outline"],
                bbox=tuple(g["bbox"]) if g["bbox"] else None,  # type: ignore[arg-type]
                dx=g.get("dx", 0),
            )
            for key, g in data["glyphs"].items()
        }
        self.specials: dict[str, set[SpecialColor]] = {}
        for key in self.glyphs:
            if key.startswith("special:"):
                _, name, color, _ = key.split(":")
                self.specials.setdefault(name, set()).add(cast(SpecialColor, color))

    def __getitem__(self, key: str) -> Glyph:
        return self.glyphs[key]

    def __contains__(self, key: str) -> bool:
        return key in self.glyphs

    def supports(self, figure: Figure) -> bool:
        return figure_key(figure, "light") in self.glyphs

    def figure_glyph(self, figure: Figure, shade: Shade) -> Glyph:
        try:
            return self.glyphs[figure_key(figure, shade)]
        except KeyError:
            raise KeyError(f"the GC fonts have no glyph for {figure}") from None

    def square_glyph(self, shade: Shade) -> Glyph:
        return self.glyphs[f"square:{shade}"]


def figure_key(figure: Figure, shade: Shade) -> str:
    if isinstance(figure, Piece):
        return f"piece:{figure.kind}:{figure.color}:{figure.angle}:{figure.variant}:{shade}"
    if isinstance(figure, Special):
        return f"special:{figure.name}:{figure.color}:{shade}"
    raise TypeError(figure)


@cache
def load_catalog() -> Catalog:
    text = resources.files("gcdiagram").joinpath("data/catalog.json").read_text()
    return Catalog(json.loads(text))
